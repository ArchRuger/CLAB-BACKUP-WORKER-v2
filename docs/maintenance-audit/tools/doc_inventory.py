#!/usr/bin/env python3
"""Inventory every tracked Markdown file with its size, age and documentation class.

The class follows docs/REPOSITORY-MAINTENANCE.md: a *living guide* describes the current release and
names no version of its own; a *history* file (the release records, the archive, the per-stream folders
listed in verify-release.py's exemption) may name any release; *agent* files are the `.claude/` tree and
the handoff file; *vm-local* is the 2026-10-02 VM snapshot (not for merging, kept on main as history);
*vendored* is third-party content that is never edited in place. The campaign-2 documentation audit
assigns each class to a bounded domain; this tool only lists, it changes nothing.

    python3 docs/maintenance-audit/tools/doc_inventory.py            # the table on stdout
    python3 docs/maintenance-audit/tools/doc_inventory.py --write    # docs/parity-campaign/DOCS-INVENTORY.md (a campaign record: history-exempt, because historical paths name releases)
    python3 docs/maintenance-audit/tools/doc_inventory.py --json     # one object per file

Standard library only; run from anywhere inside the checkout.
"""
import argparse
import json
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

HISTORY_FOLDERS = ('docs/archive/', 'docs/redesign/', 'docs/ui-review-001/', 'docs/multi-platform-restore/',
                   'docs/save-location-fix/', 'docs/student-quick-start/', 'docs/ui-ux-cleanup/', 'docs/technical-audit/',
                   'docs/netlab-integration/', 'docs/netlab-ui-qa/', 'docs/ui-ux-changes-2/', 'docs/uiux-email-2026-10-03/',
                   'docs/git-redesign/', 'docs/parity-campaign/', 'docs/maintenance-audit/', 'docs/lab-builder/',
                   'docs/installer-tui/')
HISTORY_FILES = ('docs/CHANGELOG.md', 'clab-backup-ui/VALIDATION.md', 'agent instructions.md')
VENDORED = ('.claude/skills/',)
NOTICE = re.compile(r'(?i)\b(superseded|historical|history|archived|not for merging|retired|no longer current|dated record)\b')


def checkout_root():
    out = subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True, check=True)
    return Path(out.stdout.strip())


def classify(path):
    if path.startswith('vm-local/'): return 'vm-local'
    if path.startswith(VENDORED): return 'vendored' if '/skills/' in path and not path.endswith('SKILL.md.license') else 'agent'
    if path.startswith('.claude/') or path in ('CLAUDE.md', 'agent instructions.md', 'docs/AGENT-ROUTING.md'): return 'agent'
    if path in HISTORY_FILES or path.startswith(HISTORY_FOLDERS): return 'history'
    if path.startswith('docs/') or path.endswith('README.md') or path.endswith('NODE-FEATURES.md') or path.startswith('deploy/'): return 'guide'
    return 'other'


def inventory(root):
    files = subprocess.run(['git', 'ls-files', '-z', '*.md', '**/*.md'], cwd=root, capture_output=True, text=True, check=True).stdout.split('\0')
    rows = []
    for path in sorted(p for p in files if p):
        full = root / path
        if full.is_symlink():
            rows.append({'path': path, 'class': 'symlink', 'bytes': 0, 'lines': 0, 'last_commit': '', 'links': 0, 'notice': '', 'title': '-> ' + os.readlink(full)})
            continue
        text = full.read_text(encoding='utf8', errors='replace')
        date = subprocess.run(['git', 'log', '-1', '--format=%cs', '--', path], cwd=root, capture_output=True, text=True).stdout.strip()
        head = '\n'.join(text.splitlines()[:15])
        title = next((line.lstrip('# ').strip() for line in text.splitlines() if line.startswith('#')), '')
        # A title that names a release (the history files do) is masked: this inventory is a living record and names none.
        title = re.sub(r'\b\d+\.\d+\.\d+\b', 'x.y.z', title)
        rows.append({'path': path, 'class': classify(path), 'bytes': len(text.encode()), 'lines': text.count('\n') + 1,
                     'last_commit': date, 'links': len(re.findall(r'\]\(', text)), 'notice': (NOTICE.search(head) or [''])[0] if NOTICE.search(head) else '',
                     'title': title[:90]})
    return rows


def table(rows):
    counts = Counter(r['class'] for r in rows)
    lines = ['# Documentation inventory', '',
             'Generated by `docs/maintenance-audit/tools/doc_inventory.py` (campaign 2, D01). One row per tracked Markdown file;',
             'the class follows `docs/REPOSITORY-MAINTENANCE.md` and decides which audit domain owns the file. A notice is the',
             'first word in the file head that marks it as history (`superseded`, `historical`, `not for merging`, …).', '',
             'Counts: ' + ', '.join('%s %d' % (k, v) for k, v in sorted(counts.items())) + ', total %d.' % len(rows), '',
             '| Path | Class | KB | Lines | Last commit | Links | Notice | Title |', '|---|---|---|---|---|---|---|---|']
    for r in rows:
        lines.append('| `%s` | %s | %.1f | %d | %s | %d | %s | %s |' % (r['path'], r['class'], r['bytes'] / 1024, r['lines'], r['last_commit'], r['links'], r['notice'], r['title'].replace('|', '\\|')))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--write', action='store_true', help='write docs/parity-campaign/DOCS-INVENTORY.md')
    parser.add_argument('--json', action='store_true', help='print one JSON object per file')
    args = parser.parse_args()
    root = checkout_root()
    rows = inventory(root)
    if args.json:
        for r in rows: print(json.dumps(r))
        return 0
    text = table(rows)
    if args.write:
        (root / 'docs/parity-campaign/DOCS-INVENTORY.md').write_text(text)
        print('Wrote docs/parity-campaign/DOCS-INVENTORY.md (%d files).' % len(rows))
    else:
        sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
